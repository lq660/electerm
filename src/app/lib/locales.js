function applyLocaleOverrides (lang, id) {
  // 2026-07-06 coder(lq): Keep product-specific copy outside the upstream locale package so reinstalling dependencies does not lose it.
  const fallback = id.startsWith('zh_')
    ? localeOverrides.zh_cn
    : localeOverrides.en_us
  Object.assign(lang.lang, fallback, localeOverrides[id])
  return lang
}

function getOsLocale () {
  return require('os-locale-s')
    .osLocale()
    .catch(() => '')
}

async function loadLocales () {
  const sysLocale = await getOsLocale() || defaultLang
  const path = (isDev
    ? '../../'
    : '') +
    '../node_modules/@electerm/electerm-locales/dist/cjs'
  const localeFolder = resolve(__dirname, path)
  // languages array
  const langs = require(resolve(localeFolder, 'list.json'))
    .map(fileName => {
      const filePath = resolve(localeFolder, fileName)
      const id = fileName.replace('.js', '')
      const lang = applyLocaleOverrides(require(filePath), id)
      return {
        path: filePath,
        id,
        name: lang.name,
        reg: lang.match,
        lang: lang.lang
      }
    })
  const langMap = langs.reduce((prev, l) => {
    prev[l.id] = l
    return prev
  }, {})
  return {
    langs,
    langMap,
    sysLocale
  }
}

function findLang (langs, la) {
  let res = false
  for (const l of langs) {
    res = new RegExp(l.reg).test(la)
    if (res) {
      res = l.id
      break
    }
  }
  return res
}

const getLang = (config, sysLocale, langs) => {
  // 2026-07-11 coder(lq): 云舵面向中文场景，旧 electerm 配置里保存的 en_us 需要按新的产品默认语言处理。
  if (config.language === 'en_us' && packInfo.productName === '云舵工作台') {
    return defaultLang
  }
  if (config.language) {
    return config.language
  }
  let l = sysLocale
  l = l ? l.toLowerCase().replace('-', '_') : defaultLang
  return findLang(langs, l) || defaultLang
}

exports.getLang = getLang
exports.loadLocales = loadLocales
